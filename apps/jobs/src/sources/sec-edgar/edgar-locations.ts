/** First wins, and states are listed first: "GEORGIA" is both the US state (GA)
 *  and the country (2Q), and a description alone cannot tell them apart — the
 *  state is overwhelmingly the likelier filer. The code lookup has no such
 *  ambiguity, which is why sources prefer it when they have the code. */
const BY_DESCRIPTION = new Map<string, string | null>();
for (const [description, country] of Object.values(EDGAR_LOCATIONS)) {
  const key = description.toUpperCase();
  if (!BY_DESCRIPTION.has(key)) BY_DESCRIPTION.set(key, country);
}
// "CANADA (Federal Level)" is how the table names Z4; filers' hq strings just say CANADA.
BY_DESCRIPTION.set('CANADA', 'CA');

/** ISO country for an EDGAR location code ("CA" → US, "X0" → GB), or null for an
 *  unknown or unmappable code. Case-insensitive. */
export function countryFromEdgarCode(code: string | null | undefined): string | null {
  const key = (code ?? '').trim().toUpperCase();
  return EDGAR_LOCATIONS[key]?.[1] ?? null;
}

/** ISO country for an EDGAR location description ("UNITED KINGDOM" → GB,
 *  "CALIFORNIA" → US, "ONTARIO, CANADA" → CA), or null. Case-insensitive. */
export function countryFromEdgarDescription(description: string | null | undefined): string | null {
  const key = (description ?? '').trim().replace(/\s+/g, ' ').toUpperCase();
  return BY_DESCRIPTION.get(key) ?? null;
}
